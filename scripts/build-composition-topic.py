"""Extract the full camera/framing subgroup, not the mixed art/meta category.
Usage: python scripts/build-composition-topic.py <tag-library-root> <output-ts>
"""
import csv
import json
import sys
from pathlib import Path

source, target = map(Path, sys.argv[1:])
matches = sorted(source.glob("02*/12_*_*.csv"))
if len(matches) != 1:
    raise ValueError("Expected one version of the source camera taxonomy")
with matches[0].open(encoding="utf-8-sig", newline="") as handle:
    tags = sorted({r["D站英文标签"] for r in csv.DictReader(handle)
                   if r["细分用途"] == "镜头景别与拍摄视角"})
if not {"from_above", "dutch_angle", "full_body"} <= set(tags):
    raise ValueError("Camera taxonomy missing expected entries")
target.write_bytes(("// Generated by scripts/build-composition-topic.py; do not edit by hand.\nexport const sourceCameraTags: string[] = " + json.dumps(tags, ensure_ascii=False, indent=2) + ";\n").encode("utf8"))
