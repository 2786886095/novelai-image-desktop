import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = fs.readFileSync(path.join(root, "shared/tavern-image-guidance.json"), "utf8").replace(/\r\n/g, "\n").trim();
JSON.parse(source);
if (source.includes("'''")) throw new Error("Dart raw string delimiter in resource");
const dart = `// Generated by scripts/sync-tavern-image-guidance.mjs. Edit shared/tavern-image-guidance.json.
import 'dart:convert';

final Map<String, dynamic> moyuImageGuidance = jsonDecode(r'''${source}''') as Map<String, dynamic>;
`;
const target = path.join(root, "mobile/lib/agent/tavern_image_guidance_data.dart");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(target, "utf8") !== dart) throw new Error("Mobile guidance differs; run the sync script");
} else fs.writeFileSync(target, dart);
console.log("TAVERN_IMAGE_GUIDANCE_SYNC_OK");
