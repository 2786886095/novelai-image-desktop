import fs from 'node:fs/promises';
import sharp from 'sharp';
const base=new URL('./plugins/studio-responsive/',import.meta.url);
const icon=JSON.stringify('data:image/png;base64,'+(await sharp(await fs.readFile(new URL('../public/icon.png',import.meta.url))).resize(64,64).png().toBuffer()).toString('base64'));
const install=(await fs.readFile(new URL('install.js',base),'utf8')).replace(/\r\n/g,'\n').replace('export function','function').replace('__STUDIO_ICON_JSON__',icon);
const css=(await fs.readFile(new URL('responsive.css',base),'utf8')).replace(/\r\n/g,'\n');
await fs.mkdir(new URL('lib/',base),{recursive:true});
await fs.writeFile(new URL('lib/client.js',base),`// Generated by harness/build-responsive.mjs\nwindow.__ModuleLoader__.load({id:'@langbai/dsh-studio-responsive',factory(){\n${install}\nreturn {apply(ctx){ctx.effect(()=>installResponsive(${JSON.stringify(css)}));}};}});\n`);
console.log('RESPONSIVE CLIENT BUILT');
